optimizer = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=1e-4)
scheduler = CosineAnnealingLR(optimizer, T_max=EPOCHS, eta_min=1e-6)
# scaler is already defined globally in cell F64THg2jD8sP, so no need to redefine.

# ✅ Loss: bce_loss, dice_loss, and total_loss are defined globally in cell F64THg2jD8sP.
