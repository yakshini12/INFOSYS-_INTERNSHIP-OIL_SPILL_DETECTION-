# ✅ Metrics
def metrics(preds, targets, threshold=0.5):
    probs = torch.sigmoid(preds)
    preds = (probs > threshold).float()
    targets = targets.float()
    inter = (preds * targets).sum()
    union = preds.sum() + targets.sum() - inter
    dice = (2. * inter) / (preds.sum() + targets.sum() + 1e-7)
    iou = (inter + 1e-7) / (union + 1e-7)
    acc = (preds == targets).float().mean()
    return dice.item(), iou.item(), acc.item()

# History tracking lists
train_losses, val_losses = [], []
train_dices, val_dices = [], []
train_ious, val_ious = [], []
train_accs, val_accs = [], []

# ✅ Training
best_score = 0.0
for epoch in range(EPOCHS):
    model.train()
    # Initialize epoch-level accumulators
    current_train_loss = 0.0
    current_train_dice = 0.0
    current_train_iou = 0.0
    current_train_acc = 0.0
    num_train_samples = 0

    optimizer.zero_grad() # Zero gradients once at the start of the epoch for accumulation

    for i, (imgs, masks) in enumerate(tqdm(train_loader, desc=f"Epoch {epoch+1}/{EPOCHS} Training")):
        imgs, masks = imgs.to(DEVICE), masks.to(DEVICE)
        num_train_samples += imgs.size(0)

        with torch.cuda.amp.autocast(): # Use autocast directly from torch.cuda.amp
            logits = model(imgs)
            loss = total_loss(logits, masks)
        # Scale loss before backward for accumulation
        scaler.scale(loss / GRAD_ACCUM_STEPS).backward()

        if (i + 1) % GRAD_ACCUM_STEPS == 0:
            scaler.step(optimizer)
            scaler.update()
            optimizer.zero_grad() # Zero gradients after update

        d, iou, acc = metrics(logits, masks)
        current_train_loss += loss.item() * imgs.size(0)
        current_train_dice += d * imgs.size(0)
        current_train_iou += iou * imgs.size(0)
        current_train_acc += acc * imgs.size(0)

    # Perform a final optimization step if there are remaining gradients
    if (i + 1) % GRAD_ACCUM_STEPS != 0:
        scaler.step(optimizer)
        scaler.update()
        optimizer.zero_grad()

    # 🔍 Validation
    model.eval()
    current_val_loss = 0.0
    current_val_dice = 0.0
    current_val_iou = 0.0
    current_val_acc = 0.0
    num_val_samples = 0

    with torch.no_grad():
        for imgs, masks in tqdm(val_loader, desc=f"Epoch {epoch+1}/{EPOCHS} Validation"):
            imgs, masks = imgs.to(DEVICE), masks.to(DEVICE)
            num_val_samples += imgs.size(0)
            with torch.cuda.amp.autocast():
                logits = model(imgs)
                loss = total_loss(logits, masks)
            d, iou, acc = metrics(logits, masks)
            current_val_loss += loss.item() * imgs.size(0)
            current_val_dice += d * imgs.size(0)
            current_val_iou += iou * imgs.size(0)
            current_val_acc += acc * imgs.size(0)

    # ⚡ Epoch summary
    train_loss_epoch = current_train_loss / num_train_samples
    val_loss_epoch = current_val_loss / num_val_samples
    train_dice_epoch = current_train_dice / num_train_samples
    val_dice_epoch = current_val_dice / num_val_samples
    train_iou_epoch = current_train_iou / num_train_samples
    val_iou_epoch = current_val_iou / num_val_samples
    val_acc_epoch = current_val_acc / num_val_samples

    # Store history
    train_losses.append(train_loss_epoch)
    val_losses.append(val_loss_epoch)
    train_dices.append(train_dice_epoch)
    val_dices.append(val_dice_epoch)
    train_ious.append(train_iou_epoch)
    val_ious.append(val_iou_epoch)
    train_accs.append(current_train_acc / num_train_samples) # Also store train_acc
    val_accs.append(val_acc_epoch)

    print(f"Epoch [{epoch+1}/{EPOCHS}] | Train Loss: {train_loss_epoch:.4f} | Val Loss: {val_loss_epoch:.4f} | Train Dice: {train_dice_epoch:.4f} | Val Dice: {val_dice_epoch:.4f} | Val IoU: {val_iou_epoch:.4f} | Val Acc: {val_acc_epoch:.4f}")

    scheduler.step()

    # 🏆 Save best model
    score = 0.7 * val_dice_epoch + 0.3 * val_iou_epoch
    if score > best_score:
        best_score = score
        torch.save(model.state_dict(), "best_model_optimized.pth")
        print(f"✅ New best model saved with combined score {best_score:.4f}")

